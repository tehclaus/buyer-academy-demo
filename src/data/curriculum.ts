function buildCurriculum(): DayPlan[] {
  if (RAW_DAYS.length !== 20) {
    throw new Error(`Curriculum must have exactly 20 days, got ${RAW_DAYS.length}`);
  }

  return RAW_DAYS.map((raw, index) => {
    const day = index + 1;
    const dayStr = String(day).padStart(2, '0');

    if (raw.videos.length !== 5) {
      throw new Error(`Day ${day} must have exactly 5 videos, got ${raw.videos.length}`);
    }
    if (raw.quiz.length !== 10) {
      throw new Error(`Day ${day} must have exactly 10 quiz questions, got ${raw.quiz.length}`);
    }

    const knowledgeCount = raw.quiz.filter((q) => q.type === 'knowledge').length;
    const situationalCount = raw.quiz.filter((q) => q.type === 'situational').length;
    if (knowledgeCount + situationalCount !== 10) {
      throw new Error(`Day ${day} quiz questions must each be tagged 'knowledge' or 'situational'`);
    }
    if (situationalCount < 2 || situationalCount > 4) {
      throw new Error(
        `Day ${day} must have approximately 3 situational questions (7 knowledge / 3 situational), got ${situationalCount}`,
      );
    }

    const videos: Video[] = raw.videos.map((v, i) => ({
      id: `d${dayStr}v${i + 1}`,
      order: i + 1,
      title: v.title,
      description: v.description,
      durationMinutes: v.minutes,
    }));

    const quiz: QuizQuestion[] = raw.quiz.map((q, i) => ({
      id: `d${dayStr}q${i + 1}`,
      question: q.question,
      options: q.options,
      correctIndex: q.correctIndex,
      reviewVideoId: `d${dayStr}v${q.reviewVideoOrder}`,
      type: q.type,
      sourceDay: day,
    }));

    return {
      day,
      moduleId: raw.moduleId,
      title: raw.title,
      objective: raw.objective,
      videos,
      quiz,
    };
  });
}

export const CURRICULUM: DayPlan[] = buildCurriculum();

const TOTAL_VIDEO_COUNT = CURRICULUM.reduce((sum, d) => sum + d.videos.length, 0);
if (TOTAL_VIDEO_COUNT !== 100) {
  throw new Error(`Curriculum must contain exactly 100 videos, got ${TOTAL_VIDEO_COUNT}`);
}

const TOTAL_QUESTION_COUNT = CURRICULUM.reduce((sum, d) => sum + d.quiz.length, 0);
if (TOTAL_QUESTION_COUNT !== 200) {
  throw new Error(`Curriculum must contain exactly 200 quiz questions, got ${TOTAL_QUESTION_COUNT}`);
}

export function getDayPlan(day: number): DayPlan | undefined {
  return CURRICULUM.find((d) => d.day === day);
}

export function getModuleForDay(day: number): ModulePlan | undefined {
  return MODULES.find((m) => day >= m.dayStart && day <= m.dayEnd);
}

export function getAllVideos(): Video[] {
  return CURRICULUM.flatMap((d) => d.videos);
}

export function getVideoById(videoId: string): Video | undefined {
  return getAllVideos().find((v) => v.id === videoId);
}

export function getAllQuizQuestions(): QuizQuestion[] {
  return CURRICULUM.flatMap((d) => d.quiz);
}

/** Question pool for a checkpoint/certification: all questions authored for days in [dayStart, dayEnd]. */
export function getQuestionPoolForDayRange(dayStart: number, dayEnd: number): QuizQuestion[] {
  return CURRICULUM.filter((d) => d.day >= dayStart && d.day <= dayEnd).flatMap((d) => d.quiz);
}
