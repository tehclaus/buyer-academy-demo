function buildCurriculum(): DayPlan[] {
  if (RAW_DAYS.length !== 20) {
    throw new Error(`Curriculum must have exactly 20 days, got ${RAW_DAYS.length}`);
  }

  return RAW_DAYS.map((raw, index) => {
    const day = index + 1;
    const dayStr = String(day).padStart(2, '0');

    if (raw.videos.length !== 5) {
      throw new Error(`Day ${day} must have exactly 5 videos, got ${raw.videos.length}`);
    }
    if (raw.quiz.length !== 5) {
      throw new Error(`Day ${day} must have exactly 5 quiz questions, got ${raw.quiz.length}`);
    }

    const videos: Video[] = raw.videos.map((v, i) => ({
      id: `d${dayStr}v${i + 1}`,
      order: i + 1,
      title: v.title,
      description: v.description,
      durationMinutes: v.minutes,
    }));

    const quiz: QuizQuestion[] = raw.quiz.map((q, i) => ({
      id: `d${dayStr}q${i + 1}`,
      question: q.question,
      options: q.options,
      correctIndex: q.correctIndex,
      reviewVideoId: `d${dayStr}v${q.reviewVideoOrder}`,
    }));

    return {
      day,
      moduleId: raw.moduleId,
      title: raw.title,
      objective: raw.objective,
      videos,
      quiz,
    };
  });
}

export const CURRICULUM: DayPlan[] = buildCurriculum();

const TOTAL_VIDEO_COUNT = CURRICULUM.reduce((sum, d) => sum + d.videos.length, 0);
if (TOTAL_VIDEO_COUNT !== 100) {
  throw new Error(`Curriculum must contain exactly 100 videos, got ${TOTAL_VIDEO_COUNT}`);
}

export function getDayPlan(day: number): DayPlan | undefined {
  return CURRICULUM.find((d) => d.day === day);
}

export function getModuleForDay(day: number): ModulePlan | undefined {
  return MODULES.find((m) => day >= m.dayStart && day <= m.dayEnd);
}

export function getAllVideos(): Video[] {
  return CURRICULUM.flatMap((d) => d.videos);
}
